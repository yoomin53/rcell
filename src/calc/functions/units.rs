/// 접두사를 붙일 수 있는 단위 (한셀에서 `k…` 꼴로 확인한 것)
const PREFIXABLE: &[&str] = &[
    "g", "u", "m", "ang", "sec", "Pa", "atm", "mmHg", "N", "dyn", "J", "e", "c", "cal", "eV", "Wh",
    "W", "T", "ga", "K", "l",
];

/// SI 접두사. `e` 는 10 (데카), `da`·`y`·`Y` 는 없다.
const PREFIXES: &[(char, f64)] = &[
    ('E', 1e18),
    ('P', 1e15),
    ('T', 1e12),
    ('G', 1e9),
    ('M', 1e6),
    ('k', 1e3),
    ('h', 1e2),
    ('e', 1e1),
    ('d', 1e-1),
    ('c', 1e-2),
    ('m', 1e-3),
    ('u', 1e-6),
    ('n', 1e-9),
    ('p', 1e-12),
    ('f', 1e-15),
    ('a', 1e-18),
];

/// 온도 단위 차례 (C, F, K) 쌍의 `값 × A + B`
const TEMP: [&str; 3] = ["C", "F", "K"];
const TEMP_AB: [[(f64, f64); 3]; 3] = [
    [(1.0, 0.0), (1.8, 32.0), (1.0, 273.15)],
    [
        (0.555555555555556, -17.7777777777778),
        (1.0, 0.0),
        (0.555555555555556, 255.372222222222),
    ],
    [(1.0, -273.15), (1.8, -459.67), (1.0, 0.0)],
];

/// 단위 이름 → (분류, 차례, 접두사 배수). 분류 `usize::MAX` 는 온도.
fn unit(name: &str) -> Option<(usize, usize, f64)> {
    let find = |n: &str| {
        if let Some(i) = TEMP.iter().position(|t| *t == n) {
            return Some((usize::MAX, i));
        }
        CATS.iter()
            .enumerate()
            .find_map(|(c, cat)| cat.units.iter().position(|u| *u == n).map(|i| (c, i)))
    };
    if let Some((c, i)) = find(name) {
        return Some((c, i, 1.0));
    }
    let mut ch = name.chars();
    let p = ch.next()?;
    let rest = ch.as_str();
    let (_, k) = PREFIXES.iter().find(|(c, _)| *c == p)?;
    if !PREFIXABLE.contains(&rest) {
        return None;
    }
    find(rest).map(|(c, i)| (c, i, *k))
}

pub fn convert(ctx: &mut Ctx, a: &[Value]) -> Value {
    let x = try_v!(num_arg(ctx, a, 0));
    let from = try_v!(text_arg(ctx, a, 1));
    let to = try_v!(text_arg(ctx, a, 2));
    let (Some((c1, i, p1)), Some((c2, j, p2))) = (unit(&from), unit(&to)) else {
        return Value::Error(ErrorKind::NA);
    };
    if c1 != c2 {
        return Value::Error(ErrorKind::NA);
    }
    if c1 == usize::MAX {
        // 접두사를 먼저 적용한다 (CONVERT(3,"C","mK") = 3273.15, 대조 실험 misc4)
        let (k, b) = TEMP_AB[i][j];
        return num((x * p1 / p2) * k + b);
    }
    num(x * CATS[c1].m[i][j] * (p1 / p2))
}

