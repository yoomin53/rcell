/// 한셀 CONVERTK(값, 분류, 원래 단위, 바꿀 단위). 번호는 소수점 아래를 버린다. 분류는 1–24, 단위는
/// 1–11 (그 밖은 #N/A). 같은 단위끼리는 표에 없는 번호라도 값을 그대로 돌려준다.
pub fn convertk(ctx: &mut Ctx, a: &[Value]) -> Value {
    let x = try_v!(num_arg(ctx, a, 0));
    let g = try_v!(num_arg(ctx, a, 1)).trunc();
    let i = try_v!(num_arg(ctx, a, 2)).trunc();
    let j = try_v!(num_arg(ctx, a, 3)).trunc();
    if !(1.0..=24.0).contains(&g) || !(1.0..=11.0).contains(&i) || !(1.0..=11.0).contains(&j) {
        return Value::Error(ErrorKind::NA);
    }
    let (g, i, j) = (g as usize - 1, i as usize - 1, j as usize - 1);
    if i == j {
        return num(x);
    }
    if g == 4 {
        // 섭씨(1) ↔ 화씨(2)
        return match (i, j) {
            (0, 1) => num(x * 1.8 + 32.0),
            (1, 0) => num((x - 32.0) / 1.8),
            _ => Value::Error(ErrorKind::NA),
        };
    }
    match CONVERTK_TABLE[g].get(i).and_then(|r| r.get(j)) {
        Some(k) if !k.is_nan() => num(x * k),
        _ => Value::Error(ErrorKind::NA),
    }
}
